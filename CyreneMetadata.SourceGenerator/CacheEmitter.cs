using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace CyreneMetadata.SourceGenerator;

internal static class CacheEmitter
{
    public static string Emit(CollectionResult result)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated by CyreneMetadata/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine("namespace CyreneMetadata.Generated;");
        builder.AppendLine();
        builder.AppendLine("internal static class CyreneMetadataRegistration");
        builder.AppendLine("{");
        builder.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
        builder.AppendLine("    internal static void Register()");
        builder.AppendLine("    {");

        foreach (var root in result.Roots)
        {
            builder.AppendLine($"        global::CyreneMetadata.CyreneMetadataCache.RegisterDerive(typeof({TypeSymbolHelper.GetTypeOfName(root.RootType)}), new global::System.Type[]");
            builder.AppendLine("        {");
            foreach (var derived in root.DerivedTypes) builder.AppendLine($"            typeof({TypeSymbolHelper.GetTypeOfName(derived)}),");
            builder.AppendLine("        });");
        }

        foreach (var type in result.CreatableTypes)
        {
            var typeName = TypeSymbolHelper.GetTypeOfName(type);
            builder.AppendLine($"        global::CyreneMetadata.CyreneMetadataCache.RegisterCtor(typeof({typeName}), static () => new {typeName}());");
        }

        foreach (var ctor in result.ParamCtors)
        {
            var typeName = TypeSymbolHelper.GetTypeOfName(ctor.Type);
            var paramNames = ctor.Constructor.Parameters.Select(p => TypeSymbolHelper.GetFullyQualifiedName(p.Type)).ToArray();
            var types = string.Join(", ", paramNames.Select(name => $"typeof({name})"));
            var args = string.Join(", ", paramNames.Select((name, i) => $"({name})a[{i}]!"));
            builder.AppendLine($"        global::CyreneMetadata.CyreneMetadataCache.RegisterCtor(typeof({typeName}), new global::System.Type[] {{ {types} }}, static a => new {typeName}({args}));");
        }

        foreach (var root in result.PropertyRoots)
        {
            builder.AppendLine($"        global::CyreneMetadata.CyreneMetadataCache.RegisterProp(typeof({TypeSymbolHelper.GetTypeOfName(root.RootType)}), new global::CyreneMetadata.CyrenePropertyInfo[]");
            builder.AppendLine("        {");
            foreach (var property in root.Properties) EmitProperty(builder, property);
            builder.AppendLine("        });");
        }

        builder.AppendLine("    }");
        builder.AppendLine("}");

        return builder.ToString();
    }

    private static void EmitProperty(StringBuilder builder, PropertyMetadata prop)
    {
        var ownerName = TypeSymbolHelper.GetTypeOfName(prop.OwnerType);
        var propTypeName = TypeSymbolHelper.GetFullyQualifiedName(prop.PropertyType);

        builder.AppendLine("            new global::CyreneMetadata.CyrenePropertyInfo(");
        builder.AppendLine($"                {SymbolDisplay.FormatLiteral(prop.Name, true)},");
        builder.AppendLine($"                typeof({propTypeName}),");
        builder.AppendLine($"                typeof({TypeSymbolHelper.GetTypeOfName(prop.DeclaringType)}),");
        builder.AppendLine($"                {(prop.IsStatic ? "true" : "false")},");
        builder.AppendLine($"                {(prop.IsPublic ? "true" : "false")},");
        builder.AppendLine($"                {BuildGetter(prop, ownerName)},");
        builder.AppendLine($"                {BuildSetter(prop, ownerName, propTypeName)},");
        builder.AppendLine($"                {BuildAttributes(prop)}),");
    }

    private static string BuildGetter(PropertyMetadata prop, string ownerName)
    {
        if (!prop.Getter) return "null";
        if (prop.IsStatic) return $"static _ => (object?){ownerName}.{prop.Name}";
        return $"static o => (object?)(({ownerName})o!).{prop.Name}";
    }

    private static string BuildSetter(PropertyMetadata prop, string ownerName, string propTypeName)
    {
        if (!prop.Setter) return "null";
        if (prop.IsStatic) return $"static (_, v) => {ownerName}.{prop.Name} = ({propTypeName})v!";
        return $"static (o, v) => (({ownerName})o!).{prop.Name} = ({propTypeName})v!";
    }

    private static string BuildAttributes(PropertyMetadata property)
    {
        if (property.Attributes.Length == 0) return "[]";

        var sb = new StringBuilder();
        sb.Append("new global::System.Type[] { ");
        for (var i = 0; i < property.Attributes.Length; i++)
        {
            if (i > 0) sb.Append(", ");
            sb.Append($"typeof({TypeSymbolHelper.GetTypeOfName(property.Attributes[i])})");
        }
        sb.Append(" }");
        return sb.ToString();
    }
}
